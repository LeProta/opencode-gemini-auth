#!/usr/bin/env node
// Pulls the latest lib/protocol.js from hyqhyq3/dsh-gemini-oauth-bridge into
// src/antigravity/vendor/ and records the upstream commit in src/antigravity/upstream.ts.
// Review the diff (git diff src/antigravity) before committing: this is third-party code.
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "hyqhyq3/dsh-gemini-oauth-bridge";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const headers = { "User-Agent": "opencode-gemini-auth-sync", Accept: "application/vnd.github+json" };

const commitsRes = await fetch(`https://api.github.com/repos/${REPO}/commits?path=lib&per_page=1`, { headers });
if (!commitsRes.ok) throw new Error(`GitHub API ${commitsRes.status}: ${await commitsRes.text()}`);
const [latest] = await commitsRes.json();
if (!latest?.sha) throw new Error("No commit found for lib/");

const fileRes = await fetch(`https://raw.githubusercontent.com/${REPO}/${latest.sha}/lib/protocol.js`, { headers });
if (!fileRes.ok) throw new Error(`protocol.js download ${fileRes.status}`);
const source = await fileRes.text();

await writeFile(join(root, "src/antigravity/vendor/protocol.js"), source);
await writeFile(
  join(root, "src/antigravity/upstream.ts"),
  `// Generated by commands/sync-dsh-bridge.mjs — do not edit by hand.
// The vendored src/antigravity/vendor/protocol.js matches this upstream commit.
export const DSH_BRIDGE_UPSTREAM = {
  repo: "${REPO}",
  sha: "${latest.sha}",
} as const;
`,
);
console.log(`Synced ${REPO}@${latest.sha.slice(0, 7)}: ${latest.commit?.message?.split("\n")[0] ?? ""}`);
console.log("Upstream lib/index.js host logic is ported by hand in src/antigravity/client.ts; check its diff too:");
console.log(`  https://github.com/${REPO}/commits/main/lib/index.js`);
